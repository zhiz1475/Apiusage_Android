const { app, BrowserWindow } = require('electron');
const path = require('node:path');
const fs = require('node:fs');

const cases = [[320, 640], [360, 800], [393, 852], [412, 915], [800, 360], [360, 420]];
const wait = ms => new Promise(resolve => setTimeout(resolve, ms));

app.whenReady().then(async () => {
  const win = new BrowserWindow({ width: 360, height: 800, show: false, offscreen: true, frame: false, webPreferences: { contextIsolation: true, nodeIntegration: false, sandbox: true, backgroundThrottling: false } });
  const results = [];
  win.webContents.on('console-message', (_event, level, message) => {if(level>=2) console.error(message);});
  win.webContents.debugger.attach('1.3');
  try {
    for (const [width, height] of cases) {
      win.setBounds({ x: 0, y: 0, width, height });
      await win.loadFile(path.join(process.cwd(), 'mobile', 'index.html'));
      await win.webContents.debugger.sendCommand('Emulation.setEmulatedMedia', { features: [{name:'prefers-reduced-motion',value:'reduce'}] });
      await wait(360);
      const result = await win.webContents.executeJavaScript(`(async () => {
        const nav = selector => document.querySelector(selector);
        const checks = { width: innerWidth, height: innerHeight, horizontalOverflow: document.documentElement.scrollWidth > document.documentElement.clientWidth };
        const scroller = nav('.mobile-content');
        const footer = nav('.mobile-bottom-nav');
        const assert = (value, label) => { if(!value) throw new Error(innerWidth + 'x' + innerHeight + ': ' + label); };
        assert(scroller.scrollHeight > scroller.clientHeight, 'overview must have scroll range');
        scroller.scrollTop = scroller.scrollHeight;
        const saved = scroller.scrollTop;
        assert(saved > 0, 'vertical scroll must move');
        assert(nav('.section-jump').getBoundingClientRect().bottom <= footer.getBoundingClientRect().top + 1, 'last item must be reachable above nav');
        checks.scrollDistance = saved;
        checks.contentBottom = scroller.getBoundingClientRect().bottom;
        assert(checks.contentBottom <= footer.getBoundingClientRect().top + 1, 'footer must not overlay content');
        nav('.bottom-nav-item[data-target="history"]').click();
        await new Promise(r=>setTimeout(r,280));
        checks.calendarCells = nav('#mobileCalendar').children.length;
        assert(checks.calendarCells >= 28 && checks.calendarCells <= 42, 'calendar must contain one month');
        assert(nav('#mobileCalendar').scrollWidth<=nav('#mobileCalendar').clientWidth+1,'calendar must not scroll horizontally');
        assert(nav('#historyStateCard').hidden,'normal history must not show a help card');
        const month=nav('#calendarMonth').value;
        nav('#calendarPrevious').click();assert(nav('#calendarMonth').value!==month,'previous month');
        nav('#calendarNext').click();assert(nav('#calendarMonth').value===month,'next month');
        assert(nav('#calendarMonth').tagName==='BUTTON','month selector must not use native select');
        nav('#calendarMonth').focus();nav('#calendarMonth').click();
        assert(nav('#monthSheet').classList.contains('open'),'custom month sheet opens');
        const monthBounds=nav('#monthSheet .login-sheet').getBoundingClientRect();
        assert(monthBounds.top>=0&&monthBounds.bottom<=innerHeight+1,'month picker fits screen');
        assert(nav('#calendarMonth').getAttribute('aria-expanded')==='true','month expanded state');
        const year=nav('#monthPickerYear').textContent;
        nav('#monthYearPrevious').click();assert(nav('#monthPickerYear').textContent!==year,'previous year');
        assert([...document.querySelectorAll('.month-option')].some(b=>b.disabled),'months outside history must be disabled');
        nav('#monthYearNext').click();assert(nav('#monthPickerYear').textContent===year,'next year');
        const alternative=[...document.querySelectorAll('.month-option:not(:disabled)')].find(b=>b.dataset.month!==month);
        alternative.click();assert(nav('#calendarMonth').value===alternative.dataset.month,'month choice applied');
        assert(!nav('#monthSheet').classList.contains('open'),'choice closes month sheet');
        nav('#calendarMonth').click();nav('[data-month="'+month+'"]').click();
        nav('#calendarMonth').click();window.dispatchEvent(new Event('mobile-back'));
        assert(nav('#calendarMonth').getAttribute('aria-expanded')==='false','back resets expanded state');
        assert(nav('#calendarMonth').value===month,'cancel preserves month');
        checks.customMonthPicker=true;
        const days=[...document.querySelectorAll('.calendar-day:not(:disabled)')];days.at(-1).click();
        assert(nav('#calendarDate').textContent.length>0,'selected day details');
        await new Promise(r=>setTimeout(r,180));
        assert(!nav('#dayModelsPanel').hidden && document.querySelectorAll('.day-model').length>0,'date tap must expand model calls');
        const iconPair=nav('.day-model .model-icon-pair');
        assert(iconPair.querySelector('.model-icon-night').getAttribute('src').includes('/night/'),'daily models must have night icons');
        nav('.bottom-nav-item[data-target="overview"]').click();
        assert(Math.abs(scroller.scrollTop-saved)<2, 'navigation must restore scroll');
        checks.scrollRestored = true;
        assert(nav('#subscriptionBalance').textContent==='$147.76','wallet and subscriptions must be separate');
        assert(document.querySelectorAll('.mobile-bar-value').length===7,'every day must show a value');
        const amounts=[...document.querySelectorAll('.mobile-bar-value')].map(n=>Number(n.textContent));
        assert(Math.abs(amounts.reduce((a,b)=>a+b,0)-88.3)<.001,'chart total must match labels');
        document.querySelector('[data-detail="funds"]').click();
        assert(nav('#detailSheet').classList.contains('open'),'KPI tap opens details');
        assert(nav('#detailContent').textContent.includes('钱包余额')&&nav('#detailContent').textContent.includes('订阅额度'),'funds breakdown');
        nav('#detailDone').click();
        assert(nav('#accountButton').dataset.connection==='signed-out','demo must not claim connected');
        assert(nav('#lastRefreshTime').textContent.startsWith('示例'),'sample timestamp must be labelled');
        for (const target of ['history','models','settings','overview']) {
          nav('.bottom-nav-item[data-target="' + target + '"]').click();
          await new Promise(resolve => setTimeout(resolve, 40));
          checks[target] = !nav('#' + target + 'Section').hidden;
          checks[target + 'Overflow'] = document.documentElement.scrollWidth > document.documentElement.clientWidth;
          if(target==='models')assert(!document.querySelector('.model-progress')&&nav('.model-share').textContent.includes('费用占比'),'model share must be explicit');
        }
        nav('#accountButton').click();
        assert(nav('#accountSheet').classList.contains('open')&&!nav('#loginSheet').classList.contains('open'),'account action must open profile first');
        assert(nav('#profileUsername').textContent==='预览账户'&&nav('#profileState').textContent==='演示状态','preview profile must be explicit');
        assert(nav('#logoutButton').hidden,'preview must not expose real logout');
        nav('#accountLogin').click();
        checks.loginSheet = nav('#loginSheet').classList.contains('open');
        checks.loginWidth = nav('.login-sheet').getBoundingClientRect().width;
        await new Promise(r=>setTimeout(r,400));
        const sheet = nav('#loginSheet .login-sheet').getBoundingClientRect();
        const submit = nav('#loginSubmit').getBoundingClientRect();
        assert(sheet.top >= -1 && sheet.bottom <= innerHeight+1, 'sheet must fit viewport: ' + sheet.top + '...' + sheet.bottom + '/' + innerHeight);
        assert(submit.bottom <= innerHeight+1 && submit.top >= 0, 'submit must stay visible');
        assert(nav('.mobile-shell').inert, 'background must be inert during modal');
        nav('#loginPassword').value = 'local-test-placeholder';
        window.dispatchEvent(new Event('mobile-back'));
        assert(!nav('#loginSheet').classList.contains('open'), 'back must close modal');
        assert(nav('#loginPassword').value === '', 'closing must clear password');
        nav('.bottom-nav-item[data-target="models"]').click();
        window.dispatchEvent(new Event('mobile-back'));
        assert(!nav('#overviewSection').hidden, 'back from tab must return to overview');
        nav('#themeToggle').click();
        await new Promise(r=>setTimeout(r,400));
        assert(getComputedStyle(nav('#mobileToast')).backgroundColor !== getComputedStyle(nav('#mobileToast')).color, 'toast must have contrast');
        nav('#accountButton').click();
        assert(!nav('#mobileToast').classList.contains('show'), 'modal must clear old toast');
        nav('#accountClose').click();
        nav('#settingsAccount').click();
        assert(nav('#accountSheet').classList.contains('open')&&!nav('#loginSheet').classList.contains('open'),'settings account must show profile');
        nav('#accountClose').click();
        checks.accountProfile = true;
        nav('.bottom-nav-item[data-target="settings"]').click();
        const mode=document.body.dataset.theme;
        nav('#settingsTheme').click();
        assert(nav('#accentSheet').classList.contains('open'),'settings opens accent picker');
        const colorBounds=nav('#accentSheet .login-sheet').getBoundingClientRect();
        assert(colorBounds.top>=0&&colorBounds.bottom<=innerHeight+1,'accent picker fits screen');
        nav('[data-accent="forest"]').click();
        assert(document.body.dataset.theme===mode,'accent selection must not toggle light/dark');
        assert(localStorage.getItem('apiusagebar-mobile-accent')==='forest','persist accent choice');
        assert(nav('#accentValue').textContent==='松绿','settings label matches accent');
        const accent=getComputedStyle(document.body).getPropertyValue('--accent').trim();
        assert(['#315e4d','#91bca8'].includes(accent),'forest text palette');
        assert(getComputedStyle(nav('#accentDone')).backgroundColor==='rgb(49, 94, 77)','action buttons use accent');
        assert(getComputedStyle(nav('.calendar-day.level-4')).backgroundColor==='rgb(49, 94, 77)','calendar uses accent');
        assert(getComputedStyle(nav('#brandAccent')).stroke===getComputedStyle(nav('#todaySpent')).color,'wordmark matches accent');
        nav('#accentDone').click();nav('#themeToggle').click();
        assert(document.body.dataset.accent==='forest','day/night toggle preserves accent');
        nav('#settingsTheme').click();nav('[data-accent="wine"]').click();window.dispatchEvent(new Event('mobile-back'));
        assert(!nav('#accentSheet').classList.contains('open'),'back closes accent picker');
        checks.accentPicker=true;
        checks.backPolicy = true;
        return checks;
      })()`);
      results.push(result);
    }
    const failed = results.flatMap(result => Object.entries(result).filter(([key, value]) => /Overflow$/.test(key) && value).map(([key]) => `${result.width}:${key}`));
    if (failed.length) throw new Error(`mobile overflow: ${failed.join(', ')}`);
    fs.mkdirSync(path.join(process.cwd(),'dist','mobile-preview'),{recursive:true});
    fs.writeFileSync(path.join(process.cwd(),'dist','mobile-preview','interaction-checks.json'),JSON.stringify(results,null,2));
    console.log(JSON.stringify(results, null, 2));
  } catch (error) {
    console.error(error.stack || error);
    process.exitCode = 1;
  } finally {
    if (!win.isDestroyed()) win.destroy();
    app.exit(process.exitCode || 0);
  }
});
